// Capture / restore the user-local state that a Nexus update reinstall would
// otherwise wipe: enabled/disabled (a PAK's `.disabled` rename form, a UE4SS
// mod's enabled.txt) and user-edited UE4SS config files. The update flow
// snapshots BEFORE the old files are rotated away and re-applies AFTER the new
// version lands; entries whose on-disk names changed in the new version simply
// find nothing to match and are skipped.
//
// Pure fs + injected paths ({ paksPaths, ue4ssModsPath }) — no configStore /
// Electron — so unit tests can drive both functions against temp dirs.

import fs from 'fs'
import path from 'path'
import { assertSafeSegment } from '../services/path-safety.js'
import { syncUe4ssModRegistry } from './mods-registry.js'
import { scanConfigDir, resolveModConfigPath } from './mods-config.js'
import { CONFIG_EXTENSIONS } from './constants.js'
import { stripOrderPrefix } from './mods-order.js'
import logger from '../services/logger.js'

// Same file-set as the profile config snapshot (scanConfigDir only collects
// .lua/.txt whose NAME contains "config", so mod code like main.lua is never
// captured). On top of that, exclude files the NEW version must own:
//   - enabled.txt      -> captured separately as the `enabled` flag
//   - _hzmm_link.json  -> regenerated by the installer for the new pak names
//   - hzmm.config.json -> the new version's config-editor schema
//   - modmanifest.json -> the new version's UE4SS manifest
// (scanConfigDir compares lowercased basenames, so entries here are lowercase.)
const CONFIG_EXT_SET = new Set(CONFIG_EXTENSIONS)
const EXCLUDE_FILES = new Set(['enabled.txt', '_hzmm_link.json', 'hzmm.config.json', 'modmanifest.json'])

// Locate a receipt-recorded PAK on disk. Candidate names mirror
// rotateModsToBackup (mods-install.js): receipts store the base name with the
// extension and `_P` suffix stripped.
function findPakOnDisk(paksPaths, name) {
  for (const base of [`${name}_P.pak`, `${name}.pak`]) {
    for (const dir of paksPaths) {
      if (fs.existsSync(path.join(dir, base))) return { dir, base, enabled: true }
      if (fs.existsSync(path.join(dir, `${base}.disabled`))) return { dir, base, enabled: false }
    }
  }
  return null
}

// Snapshot the current state of a receipt's localMods ({ name, modType }[]).
// Returns entries only for mods actually found on disk.
export function captureModState({ paksPaths, ue4ssModsPath }, localMods) {
  const state = []
  for (const lm of Array.isArray(localMods) ? localMods : []) {
    if (!lm || !lm.name || !lm.modType) continue
    // Receipts live in configStore (renderer-writable data) — keep names a
    // flat segment before they touch fs paths, like the IPC-handler guards.
    try { assertSafeSegment('modName', lm.name) } catch { continue }

    if (lm.modType === 'PAK') {
      const found = findPakOnDisk(paksPaths || [], lm.name)
      // coreName: the receipt name without any load-order prefix (z1_ etc.).
      // A reinstall lands the archive's ORIGINAL filename, so restore needs
      // both names to re-apply the user's ordering (see restoreModState).
      if (found) state.push({ modType: 'PAK', name: lm.name, coreName: stripOrderPrefix(lm.name), enabled: found.enabled })
    } else if (lm.modType === 'UE4SS' && ue4ssModsPath) {
      const modDir = path.join(ue4ssModsPath, lm.name)
      let isDir = false
      try { isDir = fs.statSync(modDir).isDirectory() } catch { /* not on disk */ }
      if (!isDir) continue

      const configs = {}
      try {
        scanConfigDir(modDir, '', CONFIG_EXT_SET, EXCLUDE_FILES, (relPath, fullPath) => {
          try { configs[relPath] = fs.readFileSync(fullPath, 'utf-8') } catch { /* unreadable — skip */ }
        })
      } catch (err) {
        logger.warn(`captureModState: config scan failed for ${lm.name}: ${err.message}`)
      }
      state.push({
        modType: 'UE4SS',
        name: lm.name,
        enabled: fs.existsSync(path.join(modDir, 'enabled.txt')),
        configs,
      })
    }
  }
  return state
}

// Re-apply a captured snapshot after the new version landed. Enabled-state is
// enforced in both directions: a reinstalled PAK always lands enabled, and a
// UE4SS mod lands with whatever enabled.txt its archive shipped — neither
// reflects what the user had. Config files are written back atomically through
// the same traversal-safe resolution as profile restore. Everything is
// per-entry best-effort: one locked file must not abort the rest.
export function restoreModState({ paksPaths, ue4ssModsPath }, state, { renamePak } = {}) {
  const summary = { enabledRestored: 0, configsRestored: 0, orderRestored: 0 }
  for (const entry of Array.isArray(state) ? state : []) {
    if (!entry || !entry.name || !entry.modType) continue
    try { assertSafeSegment('modName', entry.name) } catch { continue }

    if (entry.modType === 'PAK') {
      // Re-apply a load-order prefix the reinstall dropped: the pre-update pak
      // was e.g. z1_CoolMod (user made it win a conflict) but the new archive
      // landed as plain CoolMod. Rename it back via the caller-supplied
      // renamePak (renamePakEverywhere bound to real paths), which also
      // re-migrates the filename-keyed stores.
      if (renamePak && entry.coreName && entry.coreName !== entry.name && !findPakOnDisk(paksPaths || [], entry.name)) {
        const landed = findPakOnDisk(paksPaths || [], entry.coreName)
        if (landed) {
          const from = landed.base
          const to = landed.base.replace(entry.coreName, entry.name)
          try {
            renamePak(from, to)
            summary.orderRestored++
          } catch (err) {
            logger.warn(`restoreModState: load-order rename failed for ${entry.name}: ${err.message}`)
          }
        }
      }
      const found = findPakOnDisk(paksPaths || [], entry.name)
      if (!found || found.enabled === entry.enabled) continue
      const enabledPath = path.join(found.dir, found.base)
      const disabledPath = `${enabledPath}.disabled`
      try {
        if (entry.enabled) fs.renameSync(disabledPath, enabledPath)
        else fs.renameSync(enabledPath, disabledPath)
        summary.enabledRestored++
      } catch (err) {
        logger.warn(`restoreModState: PAK toggle failed for ${entry.name}: ${err.message}`)
      }
    } else if (entry.modType === 'UE4SS' && ue4ssModsPath) {
      const modDir = path.join(ue4ssModsPath, entry.name)
      if (!fs.existsSync(modDir)) continue

      for (const [relPath, content] of Object.entries(entry.configs || {})) {
        if (typeof content !== 'string') continue
        let resolved
        try {
          resolved = resolveModConfigPath(ue4ssModsPath, entry.name, relPath)
        } catch (err) {
          logger.warn(`restoreModState: skipping unsafe config path ${entry.name}/${relPath}: ${err.message}`)
          continue
        }
        try {
          fs.mkdirSync(path.dirname(resolved), { recursive: true })
          // Atomic tmp+rename, same as profile config restore.
          const tmp = `${resolved}.tmp`
          fs.writeFileSync(tmp, content, 'utf-8')
          fs.renameSync(tmp, resolved)
          summary.configsRestored++
        } catch (err) {
          logger.warn(`restoreModState: config write failed for ${entry.name}/${relPath}: ${err.message}`)
        }
      }

      const enabledFile = path.join(modDir, 'enabled.txt')
      const isEnabled = fs.existsSync(enabledFile)
      try {
        if (entry.enabled && !isEnabled) {
          fs.writeFileSync(enabledFile, '', 'utf-8')
          syncUe4ssModRegistry(ue4ssModsPath, entry.name, true)
          summary.enabledRestored++
        } else if (!entry.enabled && isEnabled) {
          fs.unlinkSync(enabledFile)
          syncUe4ssModRegistry(ue4ssModsPath, entry.name, false)
          summary.enabledRestored++
        }
      } catch (err) {
        logger.warn(`restoreModState: enabled-state restore failed for ${entry.name}: ${err.message}`)
      }
    }
  }
  return summary
}
